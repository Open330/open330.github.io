#!/usr/bin/env node
// Renders the Projects section of index.html statically from the org projects feed.
// Zero dependencies; Node >= 20.
//
//   node scripts/build-projects.mjs            # fetch feed, fall back to data/projects.json
//   node scripts/build-projects.mjs --offline  # use data/projects.json only
//
// Rewrites everything between <!-- projects:start --> and <!-- projects:end --> in index.html.
// When the remote feed is fetched successfully, data/projects.json is refreshed as well.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FEED_URL = 'https://raw.githubusercontent.com/Open330/.github/main/profile/projects.json';
const DATA_PATH = join(ROOT, 'data', 'projects.json');
const INDEX_PATH = join(ROOT, 'index.html');
const START = '<!-- projects:start -->';
const END = '<!-- projects:end -->';
const offline = process.argv.includes('--offline');

const LANG_COLORS = {
  TypeScript: '#3178c6', JavaScript: '#f1e05a', Rust: '#dea584', Swift: '#f05138',
  Python: '#3572a5', Go: '#00add8', Shell: '#89e051', HTML: '#e34c26', CSS: '#563d7c',
  Kotlin: '#a97bff', Java: '#b07219', 'C++': '#f34b7d', C: '#555555', Ruby: '#701516', Dart: '#00b4ab',
};

const esc = (s) => String(s ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

function validate(feed) {
  if (!feed || !Array.isArray(feed.projects)) throw new Error('feed missing "projects" array');
  for (const p of feed.projects) {
    if (typeof p.name !== 'string' || typeof p.url !== 'string') throw new Error('project missing name/url');
  }
  return feed;
}

async function loadFeed() {
  if (!offline) {
    try {
      const res = await fetch(FEED_URL, { headers: { 'user-agent': 'open330-landing-build' } });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const feed = validate(await res.json());
      if (feed.projects.length === 0) throw new Error('remote feed is empty');
      writeFileSync(DATA_PATH, JSON.stringify(feed, null, 2) + '\n');
      console.log(`feed: remote (${feed.projects.length} projects)`);
      return feed;
    } catch (err) {
      console.warn(`feed: remote unavailable (${err.message}); using ${DATA_PATH}`);
    }
  }
  const feed = validate(JSON.parse(readFileSync(DATA_PATH, 'utf8')));
  console.log(`feed: local (${feed.projects.length} projects)`);
  return feed;
}

function sortProjects(projects) {
  return [...projects].sort((a, b) =>
    ((b.stars ?? 0) - (a.stars ?? 0)) || String(b.pushed_at ?? '').localeCompare(String(a.pushed_at ?? '')));
}

const STAR_ICON = '<svg width="13" height="13" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="M12 2l3.09 6.26L22 9.27l-5 4.87 1.18 6.88L12 17.77l-6.18 3.25L7 14.14 2 9.27l6.91-1.01L12 2z"/></svg>';
const TAG_ICON = '<svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M20.59 13.41l-7.17 7.17a2 2 0 0 1-2.83 0L2 12V2h10l8.59 8.59a2 2 0 0 1 0 2.82z"/><line x1="7" y1="7" x2="7.01" y2="7"/></svg>';

function renderCard(p) {
  const homepage = p.homepage && /^https?:\/\//.test(p.homepage) ? p.homepage : null;
  const lang = p.language ? `<span class="project-lang"><span class="project-lang-dot" style="background:${LANG_COLORS[p.language] || 'var(--muted)'}"></span>${esc(p.language)}</span>` : '';
  const stars = `<span class="project-stars" title="GitHub stars">${STAR_ICON}${Number(p.stars ?? 0)}</span>`;
  const release = p.latest_release ? `<span class="project-release" title="Latest release">${TAG_ICON}${esc(p.latest_release)}</span>` : '';
  const desc = p.description ? esc(p.description) : 'No description yet.';
  const links = [
    `<a href="${esc(p.url)}" target="_blank" rel="noopener">GitHub</a>`,
    homepage ? `<a href="${esc(homepage)}" target="_blank" rel="noopener">Website</a>` : '',
  ].filter(Boolean).join('\n        ');
  return `    <article class="feature-card project-card">
      <div class="project-head">
        <h3><a href="${esc(p.url)}" target="_blank" rel="noopener">${esc(p.name)}</a></h3>
        ${stars}
      </div>
      <p>${desc}</p>
      <div class="project-meta">
        ${[lang, release].filter(Boolean).join('\n        ')}
      </div>
      <div class="project-links">
        ${links}
      </div>
    </article>`;
}

function render(feed) {
  const projects = sortProjects(feed.projects);
  const generated = feed.generated_at ? new Date(feed.generated_at).toISOString().slice(0, 10) : '';
  return `${START}
  <!-- Generated by scripts/build-projects.mjs — do not edit by hand. ${projects.length} projects, feed ${generated} -->
  <div class="features-grid projects-grid">
${projects.map(renderCard).join('\n')}
  </div>
  ${END}`;
}

const feed = await loadFeed();
const html = readFileSync(INDEX_PATH, 'utf8');
const s = html.indexOf(START), e = html.indexOf(END);
if (s < 0 || e < 0 || e < s) throw new Error('projects markers not found in index.html');
const next = html.slice(0, s) + render(feed) + html.slice(e + END.length);
if (next === html) {
  console.log('index.html: unchanged');
} else {
  writeFileSync(INDEX_PATH, next);
  console.log(`index.html: rendered ${feed.projects.length} projects`);
}
